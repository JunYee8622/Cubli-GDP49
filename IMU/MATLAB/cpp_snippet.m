function s = cpp_snippet(cal)
% CPP_SNIPPET  Calibration constants formatted for pasting into config.h.
f = @(v) strjoin(arrayfun(@(x) sprintf('%.5ff', x), v, 'UniformOutput', false), ', ');
s = sprintf(['static const float ACC_OFFSET[3] = {%s};\n' ...
             'static const float ACC_SCALE[3]  = {%s};\n' ...
             'static const float GYRO_BIAS[3]  = {%s};'], ...
            f(cal.acc_offset), f(cal.acc_scale), f(cal.gyro_bias));
end
